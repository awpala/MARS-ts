import { captureProbe } from '../units/run.mjs';
import { writeFileSync, readFileSync } from 'node:fs';

const check = process.argv.includes('--check');
const capture = captureProbe({
  source: 'tests/oracle/highlighting/HighlightingProbe.java',
  className: 'HighlightingProbe',
  golden: 'tests/oracle/highlighting/highlighting.json',
  check,
  legacySources: [
    'mars/venus/editors/jeditsyntax/tokenmarker/MIPSTokenMarker.java',
    'mars/venus/editors/jeditsyntax/tokenmarker/TokenMarker.java',
    'mars/venus/editors/jeditsyntax/tokenmarker/Token.java',
    'mars/venus/editors/jeditsyntax/KeywordMap.java',
    'mars/venus/editors/jeditsyntax/SyntaxUtilities.java'
  ]
});
const { cases: _cases, ...tables } = JSON.parse(capture.stdout);
const data =
  JSON.stringify(
    {
      _attribution:
        'Derived from MARS: copyright Pete Sanderson and Kenneth Vollmar (MIT). jEdit syntax classes: copyright 1998, 1999 Slava Pestov, 1999 Mike Dillon, 2010 Pete Sanderson. You may use and modify this package for any purpose. Redistribution is permitted, in both source and binary form, provided that this notice remains intact in all source distributions of this package. Generated by tests/oracle/highlighting/run.mjs against JDK 21.',
      ...tables
    },
    null,
    2
  ) + '\n';
const target = new URL('../../../src/lib/editor/highlighting/lexical-data.json', import.meta.url);
if (check) {
  if (JSON.stringify(JSON.parse(readFileSync(target, 'utf8'))) !== JSON.stringify(JSON.parse(data)))
    throw new Error('Generated highlighting tables differ');
} else writeFileSync(target, data);

const characterData =
  JSON.stringify(
    {
      _attribution:
        'Generated from JDK 21 java.lang.Character by HighlightingProbe.java. MARS copyright Pete Sanderson and Kenneth Vollmar (MIT).',
      jdkMajor: 21,
      probeSha256: capture.hashes['tests/oracle/highlighting/HighlightingProbe.java'],
      letterRanges: tables.letterRanges,
      digitRanges: tables.digitRanges
    },
    null,
    2
  ) + '\n';
const characterTarget = new URL('./character-data.json', import.meta.url);
if (check) {
  if (
    JSON.stringify(JSON.parse(readFileSync(characterTarget, 'utf8'))) !==
    JSON.stringify(JSON.parse(characterData))
  )
    throw new Error('Generated Java character tables differ');
} else writeFileSync(characterTarget, characterData);

if (check) {
  const engineTarget = new URL(
    '../../../src/lib/engine/assembler/tokenization/character-data.json',
    import.meta.url
  );
  if (
    JSON.stringify(JSON.parse(readFileSync(engineTarget, 'utf8'))) !==
    JSON.stringify(JSON.parse(characterData))
  )
    throw new Error('Engine Java character tables differ');
}
